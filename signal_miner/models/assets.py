"""Pydantic models for the requirement asset domain.

These entities represent the upper half of the mining pipeline that
Quackback does NOT implement — our primary differentiation.

Design references:
  - PM-Skills: define-opportunity-tree, define-problem-statement, deliver-prd
  - Product Manager Skills: opportunity-solution-tree, problem-framing-canvas
  - HyperOrbit: signal → theme → need → requirement → user story → AC → impact
  - Productboard: requirement/feature → linked evidence → themes → priority
"""

from __future__ import annotations

from pydantic import BaseModel, Field

from signal_miner.models import (
    AssetStatus,
    Confidence,
    Frequency,
    Severity,
    UTCTimestamp,
    new_id,
)

# ---------------------------------------------------------------------------
# Theme (Phase 2)
# ---------------------------------------------------------------------------

class Theme(BaseModel):
    """Theme — a semantic cluster of related signals.

    Generated by the clustering pipeline from signal embeddings.
    """

    id: str = Field(default_factory=lambda: new_id("thm"))
    name: str = Field(..., description="Short theme name")
    description: str = Field("", description="Theme description / summary")
    signal_ids: list[str] = Field(default_factory=list)
    signal_count: int = 0
    representative_quotes: list[str] = Field(
        default_factory=list, description="Top representative evidence quotes"
    )
    status: AssetStatus = AssetStatus.DRAFT
    created_at: UTCTimestamp
    updated_at: UTCTimestamp


# ---------------------------------------------------------------------------
# Pain Point (Phase 3)
# ---------------------------------------------------------------------------

class PainPoint(BaseModel):
    """Pain Point — a user pain extracted from themes and signals.

    Design: follows PM-Skills define-problem-statement methodology.
    """

    id: str = Field(default_factory=lambda: new_id("ppn"))
    theme_ids: list[str] = Field(default_factory=list, description="Related Theme IDs")
    user_segment: str = Field("", description="Target user segment experiencing this pain")
    description: str = Field(..., description="Clear description of the pain point")
    frequency: Frequency = Frequency.OCCASIONAL
    severity: Severity = Severity.MEDIUM
    business_impact: str = Field("", description="How this pain affects the business")
    evidence_signal_ids: list[str] = Field(default_factory=list)
    evidence_quotes: list[str] = Field(default_factory=list)
    status: AssetStatus = AssetStatus.DRAFT
    created_at: UTCTimestamp
    updated_at: UTCTimestamp


# ---------------------------------------------------------------------------
# Opportunity (Phase 3)
# ---------------------------------------------------------------------------

class EvidenceLink(BaseModel):
    """A link from an opportunity back to its supporting evidence."""

    signal_id: str
    raw_feedback_id: str
    quote: str
    source_type: str
    author_segment: str
    signal_summary: str
    signal_type: str
    confidence: float
    external_url: str | None = None



class PriorityScore(BaseModel):
    """Multi-factor priority score for opportunities and requirements.

    Design: combines ProductBridge revenue-weighted + HyperOrbit impact scoring.
    """

    frequency: float = Field(0.0, ge=0.0, le=1.0)
    recency: float = Field(0.0, ge=0.0, le=1.0)
    severity: float = Field(0.0, ge=0.0, le=1.0)
    revenue_impact: float = Field(0.0, ge=0.0, le=1.0)
    confidence: Confidence = 0.5
    strategic_fit: float = Field(0.0, ge=0.0, le=1.0)
    composite: float = Field(0.0, ge=0.0, le=1.0, description="Weighted composite score")


class Opportunity(BaseModel):
    """Opportunity card — a JTBD-framed opportunity derived from pain points.

    Design: follows PM-Skills define-opportunity-tree methodology.
    """

    id: str = Field(default_factory=lambda: new_id("opp"))
    pain_point_ids: list[str] = Field(default_factory=list)
    jtbd_statement: str = Field("", description="Jobs-to-be-Done statement")
    description: str = Field(..., description="Opportunity description")
    supporting_evidence: list[EvidenceLink] = Field(default_factory=list)
    assumptions: list[str] = Field(default_factory=list)
    priority: PriorityScore = Field(default_factory=PriorityScore)
    status: AssetStatus = AssetStatus.DRAFT
    created_at: UTCTimestamp
    updated_at: UTCTimestamp


# ---------------------------------------------------------------------------
# Requirement Asset (Phase 3)
# ---------------------------------------------------------------------------

class UserStory(BaseModel):
    """Standard user story format."""

    role: str = Field(..., description="As a ...")
    action: str = Field(..., description="I want to ...")
    benefit: str = Field(..., description="So that ...")

    def __str__(self) -> str:
        return f"As a {self.role}, I want to {self.action}, so that {self.benefit}."


class ImpactAssessment(BaseModel):
    """Business and user impact assessment for a requirement."""

    user_impact: str = ""
    business_impact: str = ""
    affected_segments: list[str] = Field(default_factory=list)
    estimated_reach: str = ""  # e.g. "~30% of active users"


class RequirementAsset(BaseModel):
    """Requirement Asset — a fully-formed, evidence-backed requirement.

    This is the primary output artifact of the mining pipeline.
    Every field is traceable back to original user evidence.
    """

    id: str = Field(default_factory=lambda: new_id("req"))
    opportunity_ids: list[str] = Field(default_factory=list)
    title: str = Field(..., description="Requirement title")
    user_stories: list[UserStory] = Field(default_factory=list)
    acceptance_criteria: list[str] = Field(default_factory=list)
    impact: ImpactAssessment = Field(default_factory=ImpactAssessment)
    priority: PriorityScore = Field(default_factory=PriorityScore)
    decision_reasoning: str = Field(
        "",
        description="Transparent reasoning for why this requirement was generated — key differentiator",
    )
    evidence_trail: list[EvidenceLink] = Field(
        default_factory=list,
        description="Full chain of evidence from raw feedback to this requirement",
    )
    status: AssetStatus = AssetStatus.DRAFT
    created_at: UTCTimestamp
    updated_at: UTCTimestamp
