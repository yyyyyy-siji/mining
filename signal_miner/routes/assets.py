@router.get("/requirements/{req_id}/evidence-trail", summary="Get requirement evidence trail details")
async def get_requirement_evidence_trail(req_id: str) -> dict:
    """Get full evidence trail details for a requirement asset."""
    session_factory = get_session_factory()
    async with session_factory() as session:
        row = await session.get(RequirementAssetRow, req_id)
        if not row:
            raise HTTPException(status_code=404, detail=f"Requirement {req_id} not found")

        # Perform validation using validate_evidence_chain
        validation_report = await validate_evidence_chain(req_id, session=session)

        # Build complete information for each evidence link
        evidence_links = []
        for link in (row.evidence_trail or []):
            sig_id = link.get("signal_id")
            rfb_id = link.get("raw_feedback_id")

            # Fetch Signal and RawFeedback if they exist
            sig = await session.get(SignalRow, sig_id) if sig_id else None
            rfb = await session.get(RawFeedbackRow, rfb_id) if rfb_id else None

            rfb_preview = ""
            if rfb and rfb.content:
                text = rfb.content.get("text") or rfb.content.get("body") or rfb.content.get("content") or ""
                rfb_preview = text[:200]

            # Compute a UI-safe source_url. Preserve external_url separately as
            # raw provenance, but do not expose demo/placeholder URLs as a
            # clickthrough.
            _resolved_source_url = None
            if rfb:
                _resolved_source_url = resolve_clickable_source_url(
                    source_type=rfb.source_type,
                    external_id=rfb.external_id,
                    external_url=rfb.external_url,
                    context=rfb.context if isinstance(rfb.context, dict) else {},
                    source_id=rfb.source_id,
                )
            if not _resolved_source_url:
                _resolved_source_url = resolve_clickable_source_url(
                    source_type=link.get("source_type") or "",
                    external_id=None,
                    external_url=link.get("source_url") or link.get("external_url"),
                    context={},
                )

            evidence_links.append({
                "signal_id": sig_id or "",
                "signal_summary": sig.summary if sig else (link.get("signal_summary") or ""),
                "signal_type": sig.signal_type if sig else (link.get("signal_type") or ""),
                "quote": link.get("quote") or "",
                "confidence": sig.confidence if sig else (link.get("confidence") or 0.0),
                "source_type": rfb.source_type if rfb else (link.get("source_type") or ""),
                "author_segment": link.get("author_segment") or "",
                "raw_feedback_id": rfb_id or "",
                "raw_feedback_preview": rfb_preview,
                "external_url": rfb.external_url if rfb else link.get("external_url"),
                "source_url": _resolved_source_url,
            })

        return {
            "requirement_id": req_id,
            "title": row.title,
            "evidence_links": evidence_links,
            "validation": {
                "total_links": validation_report.total_links,
                "valid_links": validation_report.valid_links,
                "broken_links": [
                    {
                        "signal_id": bl.signal_id,
                        "raw_feedback_id": bl.raw_feedback_id,
                        "reason": bl.reason,
                    }
                    for bl in validation_report.broken_links
                ],
                "is_valid": validation_report.is_valid,
            },
        }


@router.get("/evidence/validate", summary="Validate all evidence chains")
async def validate_all_requirements_evidence() -> dict:
    """Validate all evidence chains and return a summary report."""
    session_factory = get_session_factory()
    async with session_factory() as session:
        reports = await validate_all_evidence_chains(session=session)

        total_requirements = len(reports)
        fully_valid = sum(1 for r in reports if r.is_valid)
        has_issues = total_requirements - fully_valid

        return {
            "total_requirements": total_requirements,
            "fully_valid": fully_valid,
            "has_issues": has_issues,
            "reports": [
                {
                    "requirement_id": r.requirement_id,
                    "total_links": r.total_links,
                    "valid_links": r.valid_links,
                    "broken_links": [
                        {
                            "signal_id": bl.signal_id,
                            "raw_feedback_id": bl.raw_feedback_id,
                            "reason": bl.reason,
                        }
                        for bl in r.broken_links
                    ],
                    "is_valid": r.is_valid,
                }
                for r in reports
            ],
        }


