async def _clickable_source_url_for_link(session, link: dict) -> str | None:
    """Return a UI-safe source URL for an evidence link."""
    rfb_id = link.get("raw_feedback_id")
    rfb = await session.get(RawFeedbackRow, rfb_id) if rfb_id else None
    if rfb:
        return resolve_clickable_source_url(
            source_type=rfb.source_type,
            external_id=rfb.external_id,
            external_url=rfb.external_url,
            context=rfb.context if isinstance(rfb.context, dict) else {},
            source_id=rfb.source_id,
        )

    return resolve_clickable_source_url(
        source_type=link.get("source_type") or "",
        external_id=None,
        external_url=link.get("source_url") or link.get("external_url"),
        context={},
    )


async def _enrich_evidence_links(session, links: list[dict]) -> list[dict]:
    """Attach UI-safe ``source_url`` values while preserving raw provenance."""
    enriched = []
    for link in links:
        enriched_link = dict(link)
        enriched_link["source_url"] = await _clickable_source_url_for_link(session, link)
        rfb_id = link.get("raw_feedback_id")
        rfb = await session.get(RawFeedbackRow, rfb_id) if rfb_id else None
        if rfb:
            enriched_link["external_url"] = rfb.external_url
        enriched.append(enriched_link)
    return enriched


