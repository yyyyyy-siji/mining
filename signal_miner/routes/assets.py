@router.get("/themes", response_model=list[ThemeSummary], summary="List themes")
async def list_themes(
    status_filter: str | None = None,
    profile: str | None = None,
    version_id: str | None = None,
    limit: int = 50,
) -> list[ThemeSummary]:
    """List generated themes (semantic clusters of signals).

    Phase 7: ``profile`` filters by ``ThemeRow.pipeline_profile``.
    """
    session_factory = get_session_factory()
    async with session_factory() as session:
        stmt = select(ThemeRow).order_by(ThemeRow.signal_count.desc())
        if status_filter:
            stmt = stmt.where(ThemeRow.status == status_filter)
        if profile:
            stmt = stmt.where(ThemeRow.pipeline_profile == profile)
        if version_id and version_id != "all":
            stmt = stmt.where(ThemeRow.version_id == version_id)
        stmt = stmt.limit(limit)
        result = await session.execute(stmt)
        rows = result.scalars().all()
        return [
            ThemeSummary(
                id=r.id, name=r.name, description=r.description,
                signal_count=r.signal_count,
                representative_quotes=r.representative_quotes or [],
                status=r.status, created_at=r.created_at,
            )
            for r in rows
        ]


@router.get("/themes/{theme_id}", summary="Get theme details")
async def get_theme(theme_id: str) -> dict:
    """Get full theme details including linked signals."""
    session_factory = get_session_factory()
    async with session_factory() as session:
        row = await session.get(ThemeRow, theme_id)
        if not row:
            raise HTTPException(status_code=404, detail=f"Theme {theme_id} not found")

        # Fetch linked signals
        signals = []
        for sig_id in (row.signal_ids or []):
            sig = await session.get(SignalRow, sig_id)
            if sig:
                signals.append({
                    "id": sig.id, "signal_type": sig.signal_type,
                    "summary": sig.summary, "evidence": sig.evidence,
                    "confidence": sig.confidence,
                })

        return {
            "id": row.id, "name": row.name, "description": row.description,
            "signal_count": row.signal_count,
            "representative_quotes": row.representative_quotes,
            "status": row.status,
            "signals": signals,
            "created_at": row.created_at.isoformat() if row.created_at else None,
        }


