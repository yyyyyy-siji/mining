class DiscoverOpportunitiesRequest(BaseModel):
    feedback_ids: list[str] = Field(min_length=1, max_length=MAX_FEEDBACK_ITEMS)
    require_unmet_evidence: bool = Field(
        False,
        description="Require quoted current difficulty and remaining gap; false preserves legacy lead previews.",
    )


@router.post(
    "/opportunities/discover",
    response_model=DiscoveryPreview,
    summary="Preview opportunities from explicitly selected product feedback",
)
async def discover_selected_opportunities(
    body: DiscoverOpportunitiesRequest, request: Request,
) -> DiscoveryPreview:
    """Read the selected batch only; do not persist assets or processing states."""
    if any(not item or len(item) > 40 for item in body.feedback_ids):
        raise HTTPException(status_code=422, detail="材料ID为空或过长，请重新选择已导入材料。")
    if len(set(body.feedback_ids)) != len(body.feedback_ids):
        raise HTTPException(status_code=422, detail="材料ID重复，请去掉重复选择后重试。")
    session_factory = get_session_factory()
    async with session_factory() as session:
        result = await session.execute(
            select(RawFeedbackRow).where(RawFeedbackRow.id.in_(body.feedback_ids))
        )
        by_id = {row.id: row for row in result.scalars().all()}
        missing = [item for item in body.feedback_ids if item not in by_id]
        if missing:
            raise HTTPException(status_code=422, detail="所选材料不存在，请刷新材料列表后重新选择。")
        rows = [by_id[item] for item in body.feedback_ids]
        if any(row.pipeline_profile != "product_feedback" for row in rows):
            raise HTTPException(status_code=422, detail="只能选择产品反馈，不能混入视频或其他模式。")
    runtime = getattr(request.app.state, "runtime", None)
    if runtime is None or runtime.llm is None:
        raise HTTPException(status_code=503, detail="文本模型尚未就绪，请检查服务配置后重试。")
    try:
        return await discover_opportunities(
            rows, llm=runtime.llm, require_unmet_evidence=body.require_unmet_evidence,
        )
    except DiscoveryInputError as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from exc
    except DiscoveryModelError as exc:
        raise HTTPException(status_code=502, detail=str(exc)) from exc


